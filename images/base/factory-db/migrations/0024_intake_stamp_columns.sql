-- 0024: lift the intake_stamp fields from the event data into factory.event_log.
--
-- Run by factory-db-bootstrap in one transaction, as the database's NAME_owner role. The grants
-- for NAME_writer and NAME_reader come from the bootstrap (a re-apply on every run), so this file
-- has none; the view replace keeps the view's existing ones.
--
-- Builds on 0023 (every earlier column keeps its name, type and order). Adds the fields marked
-- "x-column": true in the merged schema that are not columns yet: version, area, needs_owner,
-- touches, dropped, labels_set and labels_kept. Postgres only adds columns at the end on OR
-- REPLACE, so they come last. Null for other types. `mode`, `outcome`, `reason` and `model` are
-- existing text columns. No @> and no DISTINCT ON.

