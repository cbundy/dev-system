-- 0008: lift the fields the repo line readers need into factory.event_log.
--
-- Run by factory-db-bootstrap in one transaction, as the database's NAME_owner role. The grants
-- for NAME_writer and NAME_reader come from the bootstrap (a re-apply on every run), so this file
-- has none; CREATE OR REPLACE VIEW keeps the view's existing ones.
--
-- Adds the fields marked "x-column": true in the transition, loop_entry, loop_passes, usage,
-- merged, implementer_routed, abandoned, requeued, reviewed and test_weakened schemas. Postgres
-- only adds columns at the end on OR REPLACE, so they come last and every earlier column keeps
-- its name, type and order. No @> and no DISTINCT ON.

