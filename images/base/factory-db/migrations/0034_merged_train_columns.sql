-- 0034: the merged event's merge-train fields as columns of factory.event_log and
-- factory_public.event_log: train (rode, dropped or NULL), train_reason (why a built train was
-- dropped), tested_tree (the tree CI passed) and tree_matched (whether the merge commit's tree was
-- that tree). A merge outside a train, and every older merged row, reads NULL in all four.
--
-- Run by factory-db-bootstrap in one transaction, as the database's NAME_owner role. Grants come
-- from the bootstrap, and the view replace keeps the views' existing ones.
--
-- Builds on 0031 (every earlier column keeps its name, type and order). The four columns go last in
-- both views, after merged_at, since Postgres only adds columns at the end on OR REPLACE. The
-- views are copied from 0031 with the four appended.

