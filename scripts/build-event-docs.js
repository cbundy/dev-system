#!/usr/bin/env node
"use strict";

// Builds and checks everything derived from the factory event schemas
// (docs/factory-events/schemas/*.json, the single source; docs/factory-events/README.md):
//   - docs/factory-events/REFERENCE.md: the readable reference,
//   - docs/factory-events/schemas/versions.lock.json: each version's shape without annotations,
//   - plugins/factory-loop/hooks/v2/event-schemas.ts: the same shapes as a typed constant, which the
//     shared reader (event-reader.ts) reads. The plugin cannot read docs/ at run time,
//   - images/base/factory-event-shapes.json: the same data as JSON for the image's native event writer
//     (images/base/factory-event-write.js), which checks an event's required fields at run time.
// `--check` fails (exit 1, one line per problem) when an output is stale, when a schema breaks the
// authoring rules, or when an existing version changed in a way the bump rule does not allow.
// Same shape as scripts/build-skills.js: pure builders, run({root, check, log}), a CLI.

const fs = require("node:fs");
const path = require("node:path");

const REPO_ROOT = path.join(__dirname, "..");
const REGEN_COMMAND = "npm run build:events";
const SCHEMAS_DIR = "docs/factory-events/schemas";
const OUT_REFERENCE = "docs/factory-events/REFERENCE.md";
const OUT_LOCK = `${SCHEMAS_DIR}/versions.lock.json`;
const OUT_TS = "plugins/factory-loop/hooks/v2/event-schemas.ts";
const OUT_SHAPES = "images/base/factory-event-shapes.json";
const READER = "plugins/factory-loop/hooks/v2/event-reader.ts";
const LOCK_NAME = "versions.lock.json";

// The supported keywords (docs/factory-events/README.md "Keeping the docs in step"). The reader's
// validator checks the first list; the second is documentation only.
const CHECKED = [
  "type", "enum", "const", "properties", "required", "additionalProperties", "items", "pattern",
  "minimum", "maximum", "minLength", "maxLength", "minItems", "maxItems", "format",
];
const ANNOTATIONS = ["$schema", "$id", "title", "description", "examples", "x-column", "x-issue"];
// Annotations the lock drops. x-issue stays: changing it is a shape change.
const LOCK_DROPS = new Set(["$schema", "$id", "title", "description", "examples", "x-column"]);
const SUPPORTED = new Set([...CHECKED, ...ANNOTATIONS]);
const X_ISSUE_VALUES = ["required", "optional", "none"];
const FILE_RE = /^([a-z][a-z_]*)\.v([1-9][0-9]*)\.json$/;
const LOWER_BOUNDS = ["minimum", "minLength", "minItems"];
const UPPER_BOUNDS = ["maximum", "maxLength", "maxItems"];
const ENVELOPE = "envelope";

const HEADER_TEXT = `GENERATED by scripts/build-event-docs.js from ${SCHEMAS_DIR}/*.json. Do not edit this file: edit the schemas, then run \`${REGEN_COMMAND}\`.`;

// ---- small helpers ----

const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

function sortDeep(v) {
  if (Array.isArray(v)) return v.map(sortDeep);
  if (!isObj(v)) return v;
  const out = {};
  for (const k of Object.keys(v).sort()) out[k] = sortDeep(v[k]);
  return out;
}

const byJson = (a, b) => {
  const x = JSON.stringify(a);
  const y = JSON.stringify(b);
  return x < y ? -1 : x > y ? 1 : 0;
};

// The schema without annotations, keys sorted and set-like arrays (required, enum, type) ordered,
// so equal shapes compare and serialise equal. Property names are never mistaken for keywords.
function stripSchema(s) {
  if (!isObj(s)) return s;
  const out = {};
  for (const k of Object.keys(s).sort()) {
    if (LOCK_DROPS.has(k)) continue;
    const v = s[k];
    if (k === "properties" && isObj(v)) {
      out[k] = {};
      for (const name of Object.keys(v).sort()) out[k][name] = stripSchema(v[name]);
    } else if (k === "items") out[k] = stripSchema(v);
    else if ((k === "required" || k === "enum" || k === "type") && Array.isArray(v)) out[k] = [...v].sort(byJson);
    else out[k] = sortDeep(v);
  }
  return out;
}

const types = (s) => (s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type]);
const allowsNull = (s) => types(s).includes("null") || (Array.isArray(s.enum) && s.enum.includes(null));

// ---- loading ----

// Reads every schema file. Returns {schemas: [{file, name, type, version, schema}], problems}.
function loadSchemas(root) {
  const dir = path.join(root, SCHEMAS_DIR);
  const problems = [];
  const schemas = [];
  const names = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json") && f !== LOCK_NAME).sort() : [];
  for (const name of names) {
    const file = `${SCHEMAS_DIR}/${name}`;
    const m = FILE_RE.exec(name);
    if (!m) {
      problems.push(`${file}: file name does not match <type>.v<N>.json`);
      continue;
    }
    let schema;
    try {
      schema = JSON.parse(fs.readFileSync(path.join(dir, name), "utf-8"));
    } catch (err) {
      problems.push(`${file}: not valid JSON (${err.message})`);
      continue;
    }
    schemas.push({ file, name, type: m[1], version: Number(m[2]), schema });
  }
  return { schemas, problems };
}

function readLock(root) {
  const p = path.join(root, OUT_LOCK);
  if (!fs.existsSync(p)) return {};
  const parsed = JSON.parse(fs.readFileSync(p, "utf-8"));
  const out = {};
  for (const k of Object.keys(parsed)) if (k !== "_generated") out[k] = parsed[k];
  return out;
}

// ---- authoring rules ----

function checkSchema(entry, problems) {
  const { file, type, version, schema } = entry;
  const at = (field) => `${file}: ${type} v${version}${field ? ` field ${field}` : ""}`;
  if (!isObj(schema)) {
    problems.push(`${at()}: schema is not an object`);
    return;
  }
  if (schema.title !== type) problems.push(`${at()}: title is ${JSON.stringify(schema.title)}, want "${type}"`);
  if (schema.$id !== entry.name) problems.push(`${at()}: $id is ${JSON.stringify(schema.$id)}, want "${entry.name}"`);
  if (typeof schema.description !== "string" || schema.description.trim() === "") problems.push(`${at()}: description is missing or empty`);
  if (!Array.isArray(schema.examples) || schema.examples.length === 0) problems.push(`${at()}: needs at least one example in examples`);
  if (schema["x-issue"] !== undefined && !X_ISSUE_VALUES.includes(schema["x-issue"])) {
    problems.push(`${at()}: x-issue is ${JSON.stringify(schema["x-issue"])}, want one of ${X_ISSUE_VALUES.join(", ")}`);
  }
  if (type !== ENVELOPE && schema["x-issue"] === undefined) problems.push(`${at()}: x-issue is missing`);

  const walk = (s, field, top) => {
    for (const k of Object.keys(s)) {
      if (!SUPPORTED.has(k)) problems.push(`${at(field)}: unsupported keyword ${k}`);
    }
    if (s.additionalProperties !== undefined && s.additionalProperties !== false) {
      problems.push(`${at(field)}: additionalProperties must be false`);
    }
    if (s.format !== undefined && s.format !== "date-time") problems.push(`${at(field)}: unsupported format ${JSON.stringify(s.format)}`);
    if (s.items !== undefined) walk(s.items, field ? `${field}[]` : "[]");
    if (s.properties === undefined) return;
    const required = Array.isArray(s.required) ? s.required : [];
    for (const r of required) if (!(r in s.properties)) problems.push(`${at(field)}: required ${r} is not a property`);
    for (const name of Object.keys(s.properties)) {
      const p = s.properties[name];
      const f = field ? `${field}.${name}` : name;
      if (!isObj(p)) {
        problems.push(`${at(f)}: property is not an object`);
        continue;
      }
      if (typeof p.description !== "string" || p.description.trim() === "") problems.push(`${at(f)}: description is missing or empty`);
      if (!required.includes(name) && !allowsNull(p)) problems.push(`${at(f)}: is outside required, so it must allow null`);
      walk(p, f);
    }
  };
  walk(schema, "", true);
}

// ---- the bump rule ----

function sameSet(a, b) {
  return JSON.stringify([...a].sort(byJson)) === JSON.stringify([...b].sort(byJson));
}

// Differences between a locked shape and the current one that the bump rule does not allow.
// Both are stripSchema output. Returns [{field, msg}].
function diffShape(o, n, field = "") {
  const out = [];
  const add = (msg, f = field) => out.push({ field: f, msg });
  for (const k of new Set([...Object.keys(o), ...Object.keys(n)])) {
    const a = o[k];
    const b = n[k];
    if (k === "properties") {
      const oldP = a || {};
      const newP = b || {};
      for (const name of Object.keys(oldP)) {
        const f = field ? `${field}.${name}` : name;
        if (!(name in newP)) add("property removed or renamed", f);
        else out.push(...diffShape(oldP[name], newP[name], f));
      }
      for (const name of Object.keys(newP)) {
        if (name in oldP) continue;
        const f = field ? `${field}.${name}` : name;
        if ((n.required || []).includes(name)) add("new property is required", f);
        else if (!allowsNull(newP[name])) add("new property does not allow null", f);
      }
    } else if (k === "required") {
      if (!sameSet(a || [], b || [])) add("required changed");
    } else if (k === "enum") {
      if (a === undefined) add("enum added to an open field");
      else if (b === undefined) add("enum removed");
      else {
        const gone = a.filter((v) => !b.some((w) => JSON.stringify(w) === JSON.stringify(v)));
        if (gone.length) add(`enum value removed: ${gone.map((v) => JSON.stringify(v)).join(", ")}`);
      }
    } else if (LOWER_BOUNDS.includes(k)) {
      if (b !== undefined && (a === undefined || b > a)) add(`${k} tightened (${a === undefined ? "none" : a} to ${b})`);
    } else if (UPPER_BOUNDS.includes(k)) {
      if (b !== undefined && (a === undefined || b < a)) add(`${k} tightened (${a === undefined ? "none" : a} to ${b})`);
    } else if (k === "items" && isObj(a) && isObj(b)) {
      out.push(...diffShape(a, b, field ? `${field}[]` : "[]"));
    } else if (JSON.stringify(a) !== JSON.stringify(b)) {
      add(`${k} changed`);
    }
  }
  return out;
}

// ---- upgrade steps in the reader ----

function readUpgradeSteps(root) {
  const p = path.join(root, READER);
  const steps = new Set();
  if (!fs.existsSync(p)) return steps;
  const text = fs.readFileSync(p, "utf-8");
  const start = text.indexOf("export const UPGRADES");
  if (start < 0) return steps;
  for (const m of text.slice(start).matchAll(/^\s*"([a-z][a-z_]*\.v[1-9][0-9]*)"\s*:/gm)) steps.add(m[1]);
  return steps;
}

// ---- the model ----

// Everything derived from the schema files, plus the problems that block any write
// (`blocking`: lock, version and file-name problems) and the ones that do not (`problems`).
function analyse(root) {
  const { schemas, problems: nameProblems } = loadSchemas(root);
  const blocking = [...nameProblems];
  const problems = [];
  const lock = readLock(root);

  const byType = new Map();
  for (const e of schemas) {
    if (!byType.has(e.type)) byType.set(e.type, new Map());
    byType.get(e.type).set(e.version, e);
  }

  for (const e of schemas) checkSchema(e, problems);

  const steps = readUpgradeSteps(root);
  for (const [type, versions] of byType) {
    const newest = Math.max(...versions.keys());
    for (let v = 1; v <= newest; v++) {
      if (!versions.has(v)) {
        const file = `${SCHEMAS_DIR}/${type}.v${v}.json`;
        blocking.push(`${file}: ${type} v${v} is missing, but v${newest} exists${v === 1 ? " (a new type must start at v1)" : ""}`);
      }
    }
    if (type === ENVELOPE) continue;
    for (let v = 1; v < newest; v++) {
      if (versions.has(v) && !steps.has(`${type}.v${v}`)) {
        problems.push(`${READER}: ${type} v${v} has no upgrade step to v${v + 1} in UPGRADES (add "${type}.v${v}")`);
      }
    }
  }

  const present = new Set(schemas.map((e) => `${e.type}.v${e.version}`));
  for (const key of Object.keys(lock)) {
    if (!present.has(key)) blocking.push(`${SCHEMAS_DIR}/${key}.json: ${key.replace(".v", " v")} is in ${LOCK_NAME} but its file is gone (versions are never deleted)`);
  }
  const newLock = {};
  for (const e of schemas) {
    const key = `${e.type}.v${e.version}`;
    const shape = stripSchema(e.schema);
    newLock[key] = shape;
    if (!(key in lock)) continue;
    for (const d of diffShape(lock[key], shape)) {
      blocking.push(`${e.file}: ${e.type} v${e.version}${d.field ? ` field ${d.field}` : ""}: ${d.msg}; add ${e.type}.v${e.version + 1}.json`);
    }
  }
  return { schemas, byType, newLock, blocking, problems };
}

// ---- outputs ----

function buildLock(newLock) {
  return JSON.stringify({ _generated: HEADER_TEXT, ...sortDeep(newLock) }, null, 2) + "\n";
}

function currentVersions(byType) {
  const out = {};
  for (const type of [...byType.keys()].sort()) if (type !== ENVELOPE) out[type] = Math.max(...byType.get(type).keys());
  return out;
}

function buildTs(newLock, byType) {
  const lines = [
    `// ${HEADER_TEXT}`,
    "// The shapes of the factory events: docs/factory-events/schemas/ without descriptions and examples.",
    "// Read by event-reader.ts; the plugin cannot read docs/ at run time.",
    "",
    "export interface Shape {",
    "  type?: string | string[]",
    "  enum?: unknown[]",
    "  const?: unknown",
    "  properties?: Record<string, Shape>",
    "  required?: string[]",
    "  additionalProperties?: false",
    "  items?: Shape",
    "  pattern?: string",
    "  minimum?: number",
    "  maximum?: number",
    "  minLength?: number",
    "  maxLength?: number",
    "  minItems?: number",
    "  maxItems?: number",
    "  format?: string",
    '  "x-issue"?: string',
    "}",
    "",
    "// The newest version of each event type.",
    "export const CURRENT: Record<string, number> = {",
  ];
  const cur = currentVersions(byType);
  for (const [t, v] of Object.entries(cur)) lines.push(`  ${JSON.stringify(t)}: ${v},`);
  lines.push("}", "", "// Every shape of every version, keyed <type>.v<N>.", "export const SCHEMAS: Record<string, Shape> = {");
  for (const key of Object.keys(newLock).sort()) {
    const shape = newLock[key];
    lines.push(`  ${JSON.stringify(key)}: {`);
    // The keys other than properties share one line, so the file stays under the hooks size guard.
    const heads = Object.keys(shape).filter((k) => k !== "properties").map((k) => `${JSON.stringify(k)}: ${JSON.stringify(shape[k])},`);
    if (heads.length > 0) lines.push(`    ${heads.join(" ")}`);
    if (shape.properties) {
      lines.push('    "properties": {');
      for (const name of Object.keys(shape.properties)) lines.push(`      ${JSON.stringify(name)}: ${JSON.stringify(shape.properties[name])},`);
      lines.push("    },");
    }
    lines.push("  },");
  }
  lines.push("}", "");
  return lines.join("\n");
}

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

function jsonType(p) {
  if (p.const !== undefined) return `const ${JSON.stringify(p.const)}`;
  const t = types(p).filter((x) => x !== "null");
  if (t.length === 0) return p.enum ? "enum" : "any";
  if (t[0] === "array" && p.items) return `array of ${jsonType(p.items)}`;
  return t.join(" or ");
}

function bounds(p) {
  const out = [];
  if (p.enum) out.push(`one of ${p.enum.map((v) => JSON.stringify(v)).join(", ")}`);
  if (p.pattern) out.push(`pattern \`${p.pattern}\``);
  if (p.format) out.push(`format ${p.format}`);
  for (const k of [...LOWER_BOUNDS, ...UPPER_BOUNDS]) if (p[k] !== undefined) out.push(`${k} ${p[k]}`);
  if (p.items && (p.items.maxLength !== undefined || p.items.minLength !== undefined || p.items.enum)) {
    const inner = bounds(p.items);
    if (inner) out.push(`items: ${inner}`);
  }
  return out.join("; ");
}

function fieldTable(schema) {
  const required = schema.required || [];
  const rows = ["| Field | Type | Required | Nullable | Bounds or values | Column | Description |", "| --- | --- | --- | --- | --- | --- | --- |"];
  for (const [name, p] of Object.entries(schema.properties || {})) {
    rows.push(
      `| \`${name}\` | ${cell(jsonType(p))} | ${required.includes(name) ? "required" : "optional"} | ${allowsNull(p) ? "yes" : "no"} | ${cell(bounds(p))} | ${p["x-column"] ? "yes" : ""} | ${cell(p.description || "")} |`,
    );
  }
  return rows.join("\n");
}

function countingKey(description) {
  const m = /count one per (\([^)]*\)|[^.;]+)/i.exec(description || "");
  return m ? m[1].trim() : "not stated";
}

function firstSentence(s) {
  const m = /^.*?[.](?=\s|$)/s.exec(s || "");
  return m ? m[0] : s || "";
}

function buildReference(byType) {
  const out = [`<!-- ${HEADER_TEXT} -->`, "", "# Factory events reference", "", "Generated from [`schemas/`](schemas/); the decisions are in [`README.md`](README.md).", ""];
  const names = [...byType.keys()].filter((t) => t !== ENVELOPE).sort();
  const latest = (type) => byType.get(type).get(Math.max(...byType.get(type).keys())).schema;

  out.push("## Types", "", "| Type | Versions | Issue | What it is |", "| --- | --- | --- | --- |");
  for (const t of names) {
    const vs = [...byType.get(t).keys()].sort((a, b) => a - b);
    out.push(`| [\`${t}\`](#${t}) | ${vs.map((v) => `v${v}`).join(", ")} | ${latest(t)["x-issue"] || ""} | ${cell(firstSentence(latest(t).description))} |`);
  }

  const env = byType.get(ENVELOPE);
  if (env) {
    const e = env.get(Math.max(...env.keys())).schema;
    out.push("", "## Envelope", "", e.description, "", fieldTable(e), "", "Example:", "", "```json", JSON.stringify((e.examples || [])[0], null, 2), "```");

    out.push("", "## View columns", "", "`factory.event_log` has one row per event: the envelope columns, `device_seq`, and one column for each payload field marked `x-column` in the schemas. A column is null when the type lacks the field.", "");
    out.push("| Column | Type | Carried by | Description |", "| --- | --- | --- | --- |");
    for (const [name, p] of Object.entries(e.properties || {})) {
      if (name === "data") continue;
      out.push(`| \`${name}\` | ${cell(jsonType(p))} | every event | ${cell(p.description || "")} |`);
    }
    out.push("| `device_seq` | integer | every event | The line number of the event in its device's local log, set by the shipper. |");
    const lifted = new Map();
    for (const t of names) {
      for (const [v, entry] of byType.get(t)) {
        for (const [name, p] of Object.entries(entry.schema.properties || {})) {
          if (!p["x-column"]) continue;
          if (!lifted.has(name)) lifted.set(name, { types: new Set(), carriers: new Set(), desc: p.description });
          lifted.get(name).types.add(jsonType(p));
          lifted.get(name).carriers.add(byType.get(t).size > 1 ? `${t} v${v}` : t);
        }
      }
    }
    for (const name of [...lifted.keys()].sort()) {
      const l = lifted.get(name);
      out.push(`| \`${name}\` | ${cell([...l.types].join(" or "))} | ${[...l.carriers].sort().map((c) => `\`${c}\``).join(", ")} | ${cell(l.desc || "")} |`);
    }
  }

  for (const t of names) {
    const cur = latest(t);
    const vs = [...byType.get(t).keys()].sort((a, b) => a - b);
    out.push("", `## ${t}`, "", cur.description, "", `- Issue field (\`x-issue\`): ${cur["x-issue"] || "-"}`, `- Versions: ${vs.map((v) => `v${v}${v === vs[vs.length - 1] ? " (current)" : ""}`).join(", ")}`, `- Counting key: ${countingKey(cur.description)}`);
    for (const v of vs) {
      const s = byType.get(t).get(v).schema;
      out.push("", `### ${t} v${v}`, "", fieldTable(s), "", "Example:", "", "```json", JSON.stringify((s.examples || [])[0], null, 2), "```");
    }
  }
  return out.join("\n") + "\n";
}

// The same model as buildTs, as JSON for the image's native event writer.
function buildShapesJson(newLock, byType) {
  const schemas = {};
  for (const key of Object.keys(newLock).sort()) schemas[key] = newLock[key];
  return JSON.stringify({ _generated: HEADER_TEXT, current: currentVersions(byType), schemas }, null, 2) + "\n";
}

// ---- run ----

// Writes (or, with check, compares) the four outputs. Returns the list of problems, one line each.
function run({ root = REPO_ROOT, check = false, log = console.log } = {}) {
  const a = analyse(root);
  const outputs = [
    [OUT_REFERENCE, buildReference(a.byType)],
    [OUT_LOCK, buildLock(a.newLock)],
    [OUT_TS, buildTs(a.newLock, a.byType)],
    [OUT_SHAPES, buildShapesJson(a.newLock, a.byType)],
  ];
  const problems = [...a.blocking, ...a.problems];
  if (a.blocking.length > 0) return problems;
  for (const [out, want] of outputs) {
    const p = path.join(root, out);
    const have = fs.existsSync(p) ? fs.readFileSync(p, "utf-8") : null;
    if (have === want) continue;
    if (check) {
      problems.push(`${out}: out of date - run ${REGEN_COMMAND}`);
    } else {
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, want);
      log(`build-event-docs: wrote ${out}`);
    }
  }
  return problems;
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  try {
    const problems = run({ check });
    if (problems.length > 0) {
      for (const line of problems) console.error(`build-event-docs: ${line}`);
      process.exit(1);
    }
    if (check) console.log("build-event-docs: event docs, lock and shapes up to date");
  } catch (err) {
    console.error(`build-event-docs: ${err.message}`);
    process.exit(1);
  }
}

module.exports = { CHECKED, ANNOTATIONS, REGEN_COMMAND, stripSchema, diffShape, analyse, buildReference, buildLock, buildTs, run };
