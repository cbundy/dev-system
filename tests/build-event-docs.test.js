// Tests for scripts/build-event-docs.js (dev-system#691): the generated reference, version lock and
// reader shapes, the authoring rules and the bump rule. Each test builds a throwaway repo in a temp
// dir, so nothing depends on the real schemas' content.
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { test } = require("node:test");
const { spawnSync } = require("node:child_process");

const SCRIPT = path.join(__dirname, "..", "scripts", "build-event-docs.js");
const { run } = require(SCRIPT);

const DIR = "docs/factory-events/schemas";
const OUTPUTS = ["docs/factory-events/REFERENCE.md", `${DIR}/versions.lock.json`, "plugins/factory-loop/hooks/v2/event-schemas.ts"];
const READER = "plugins/factory-loop/hooks/v2/event-reader.ts";

const schema = (type, version, extra = {}) => ({
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: `${type}.v${version}.json`,
  title: type,
  description: `The ${type} event. Count one per (issue, seq).`,
  "x-issue": "required",
  type: "object",
  additionalProperties: false,
  required: ["n"],
  properties: {
    n: { type: "integer", minimum: 1, maximum: 10, description: "A number." },
    kind: { enum: ["a", "b", null], description: "A kind." },
    word: { type: ["string", "null"], pattern: "^[a-z]+$", description: "A word.", "x-column": true },
  },
  examples: [{ n: 1, kind: "a", word: "x" }],
  ...extra,
});

const ENVELOPE = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "envelope.v1.json",
  title: "envelope",
  description: "The envelope.",
  type: "object",
  additionalProperties: false,
  required: ["envelope", "data"],
  properties: { envelope: { const: 1, description: "Version." }, data: { type: "object", description: "Payload." } },
  examples: [{ envelope: 1, data: {} }],
};

function put(root, rel, v) {
  fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
  fs.writeFileSync(path.join(root, rel), typeof v === "string" ? v : JSON.stringify(v, null, 2));
}
const read = (root, rel) => fs.readFileSync(path.join(root, rel), "utf-8");
const readJson = (root, rel) => JSON.parse(read(root, rel));
const quiet = { log: () => {} };

// A built clean tree with one type "thing" at v1.
function fakeRepo(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "build-event-docs-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  put(root, `${DIR}/envelope.v1.json`, ENVELOPE);
  put(root, `${DIR}/thing.v1.json`, schema("thing", 1));
  assert.deepEqual(run({ root, ...quiet }), []);
  return root;
}

const edit = (root, name, fn) => {
  const s = readJson(root, `${DIR}/${name}`);
  fn(s);
  put(root, `${DIR}/${name}`, s);
};
const check = (root) => run({ root, check: true, ...quiet });
const snapshot = (root) => OUTPUTS.map((o) => read(root, o));

test("a clean tree passes --check and every output starts with a generated header", (t) => {
  const root = fakeRepo(t);
  assert.deepEqual(check(root), []);
  for (const o of OUTPUTS) assert.match(read(root, o).slice(0, 200), /GENERATED by scripts\/build-event-docs\.js/);
  assert.match(read(root, OUTPUTS[0]), /Counting key: \(issue, seq\)/);
  const lock = readJson(root, OUTPUTS[1]);
  assert.deepEqual(Object.keys(lock), ["_generated", "envelope.v1", "thing.v1"]);
  assert.equal(lock["thing.v1"].description, undefined);
  assert.equal(lock["thing.v1"].properties.word["x-column"], undefined);
  assert.equal(lock["thing.v1"]["x-issue"], "required");
  assert.match(read(root, OUTPUTS[2]), /"thing": 1,/);
});

test("a schema edit without a rebuild is stale in each of the three outputs", (t) => {
  for (const [i, out] of OUTPUTS.entries()) {
    const root = fakeRepo(t);
    const before = snapshot(root);
    edit(root, "thing.v1.json", (s) => s.properties.kind.enum.push("c"));
    run({ root, ...quiet });
    // Put the one output back as it was, as if the build had not written it.
    fs.writeFileSync(path.join(root, out), before[i]);
    const problems = check(root);
    assert.deepEqual(problems, [`${out}: out of date - run npm run build:events`]);
  }
});

test("a description or example change makes the reference stale but never touches the lock", (t) => {
  const root = fakeRepo(t);
  const lock = read(root, OUTPUTS[1]);
  edit(root, "thing.v1.json", (s) => {
    s.properties.n.description = "A better description.";
    s.examples.push({ n: 2 });
  });
  assert.deepEqual(check(root), [`${OUTPUTS[0]}: out of date - run npm run build:events`]);
  assert.deepEqual(run({ root, ...quiet }), []);
  assert.equal(read(root, OUTPUTS[1]), lock);
});

test("authoring rules each fail with their own message", (t) => {
  const cases = [
    ["missing schema description", (s) => delete s.description, /thing\.v1\.json: thing v1: description is missing/],
    ["missing field description", (s) => delete s.properties.n.description, /thing v1 field n: description is missing/],
    ["empty examples", (s) => (s.examples = []), /thing v1: needs at least one example/],
    ["optional not nullable", (s) => (s.properties.word.type = "string"), /thing v1 field word: is outside required, so it must allow null/],
    ["unsupported keyword", (s) => (s.properties.n.multipleOf = 2), /thing v1 field n: unsupported keyword multipleOf/],
    ["wrong $id", (s) => (s.$id = "other.v1.json"), /thing v1: \$id is "other\.v1\.json"/],
    ["wrong title", (s) => (s.title = "other"), /thing v1: title is "other"/],
  ];
  for (const [name, mutate, want] of cases) {
    const root = fakeRepo(t);
    edit(root, "thing.v1.json", mutate);
    const problems = check(root);
    assert.ok(problems.some((p) => want.test(p)), `${name}: ${problems.join("\n")}`);
  }
});

test("a bad file name fails", (t) => {
  const root = fakeRepo(t);
  put(root, `${DIR}/Thing.v1.json`, schema("thing", 1));
  put(root, `${DIR}/thing.json`, schema("thing", 1));
  const problems = check(root);
  assert.ok(problems.some((p) => /Thing\.v1\.json: file name does not match <type>\.v<N>\.json/.test(p)));
  assert.ok(problems.some((p) => /thing\.json: file name does not match/.test(p)));
});

test("the lock accepts each allowed change and build writes it", (t) => {
  const cases = [
    ["a new nullable optional field", (s) => (s.properties.extra = { type: ["string", "null"], description: "New." })],
    ["a new enum value", (s) => s.properties.kind.enum.push("c")],
    ["a lowered minimum", (s) => (s.properties.n.minimum = 0)],
    ["a removed minimum", (s) => delete s.properties.n.minimum],
    ["a raised maximum", (s) => (s.properties.n.maximum = 20)],
    ["a removed maximum", (s) => delete s.properties.n.maximum],
  ];
  for (const [name, mutate] of cases) {
    const root = fakeRepo(t);
    edit(root, "thing.v1.json", mutate);
    const problems = run({ root, ...quiet });
    assert.deepEqual(problems, [], name);
    assert.deepEqual(check(root), [], name);
    assert.notDeepEqual(readJson(root, OUTPUTS[1])["thing.v1"], readJson(fakeRepo(t), OUTPUTS[1])["thing.v1"], name);
  }
});

test("the lock refuses each forbidden change, names the next version and leaves everything unchanged", (t) => {
  const cases = [
    ["a removed field", (s) => delete s.properties.word, /field word: property removed or renamed/],
    ["a renamed field", (s) => { s.properties.words = s.properties.word; delete s.properties.word; }, /field word: property removed or renamed/],
    ["a retyped field", (s) => (s.properties.n.type = "string"), /field n: type changed/],
    ["a field made required", (s) => s.required.push("kind"), /thing v1: required changed/],
    ["a removed enum value", (s) => (s.properties.kind.enum = ["a", null]), /field kind: enum value removed: "b"/],
    ["a tightened minimum", (s) => (s.properties.n.minimum = 2), /field n: minimum tightened/],
    ["a tightened maximum", (s) => (s.properties.n.maximum = 5), /field n: maximum tightened/],
    ["a new bound", (s) => (s.properties.word.maxLength = 3), /field word: maxLength tightened/],
    ["a changed pattern", (s) => (s.properties.word.pattern = "^[a-z0-9]+$"), /field word: pattern changed/],
    ["a changed x-issue", (s) => (s["x-issue"] = "none"), /x-issue changed/],
    ["a new required field", (s) => { s.properties.more = { type: "string", description: "x" }; s.required.push("more"); }, /field more: new property is required/],
    ["a new non-null optional field", (s) => (s.properties.more = { type: "string", description: "x" }), /field more: .*(does not allow null|outside required)/],
  ];
  for (const [name, mutate, want] of cases) {
    const root = fakeRepo(t);
    const before = snapshot(root);
    edit(root, "thing.v1.json", mutate);
    for (const check_ of [true, false]) {
      const problems = run({ root, check: check_, ...quiet });
      const line = problems.find((p) => want.test(p));
      assert.ok(line, `${name}: ${problems.join("\n")}`);
      assert.match(line, /thing\.v1\.json: thing v1.*; add thing\.v2\.json$/, name);
    }
    assert.deepEqual(snapshot(root), before, `${name}: build must write nothing`);
  }
});

test("version gaps, a lost version file, a new type at v2 and a missing upgrade step fail", (t) => {
  let root = fakeRepo(t);
  put(root, `${DIR}/thing.v3.json`, schema("thing", 3));
  assert.ok(check(root).some((p) => /thing\.v2\.json: thing v2 is missing, but v3 exists/.test(p)));

  root = fakeRepo(t);
  put(root, `${DIR}/thing.v2.json`, schema("thing", 2));
  run({ root, ...quiet });
  fs.rmSync(path.join(root, DIR, "thing.v2.json"));
  assert.ok(check(root).some((p) => /thing\.v2\.json: thing v2 is in versions\.lock\.json but its file is gone/.test(p)));

  root = fakeRepo(t);
  put(root, `${DIR}/other.v2.json`, schema("other", 2));
  assert.ok(check(root).some((p) => /other\.v1\.json: other v1 is missing, but v2 exists \(a new type must start at v1\)/.test(p)));

  root = fakeRepo(t);
  put(root, `${DIR}/thing.v2.json`, schema("thing", 2));
  assert.ok(check(root).some((p) => /event-reader\.ts: thing v1 has no upgrade step to v2/.test(p)));
  put(root, READER, 'export const UPGRADES = {\n  "thing.v1": (d) => d,\n}\n');
  run({ root, ...quiet });
  assert.deepEqual(check(root), []);
});

test("a gap blocks the build and writes nothing", (t) => {
  const root = fakeRepo(t);
  const before = snapshot(root);
  put(root, `${DIR}/thing.v3.json`, schema("thing", 3));
  assert.ok(run({ root, ...quiet }).length > 0);
  assert.deepEqual(snapshot(root), before);
});

test("the generated TS stays under the size guard with one property per line", (t) => {
  const root = fakeRepo(t);
  const lines = read(root, OUTPUTS[2]).split("\n");
  assert.ok(lines.length < 600);
  assert.ok(lines.some((l) => /^ {6}"n": \{"maximum":10,"minimum":1,"type":"integer"\},$/.test(l)));
});

test("--check on the real repo passes", () => {
  const r = spawnSync("node", [SCRIPT, "--check"], { encoding: "utf-8" });
  assert.equal(r.status, 0, r.stderr);
});

test("the CLI exits 1 and prints one line per problem", (t) => {
  const root = fakeRepo(t);
  edit(root, "thing.v1.json", (s) => delete s.description);
  const problems = check(root);
  assert.equal(problems.length, 2); // the schema rule and the stale reference
  const r = spawnSync("node", ["-e", `const p=require(${JSON.stringify(SCRIPT)}).run({root:${JSON.stringify(root)},check:true});process.exit(p.length?1:0)`]);
  assert.equal(r.status, 1);
});
